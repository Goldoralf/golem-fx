//! Generates the static level-compensation tables (README §2.6) as const data: nothing is computed
//! when the plugin turns on. The curves are gfx-dsp's `shapers` (moved there verbatim from this crate's
//! curves.rs), included here.

#[path = "../gfx-dsp/src/shapers.rs"]
mod curves;

use std::fmt::Write;

fn main() {
    println!("cargo:rerun-if-changed=../gfx-dsp/src/shapers.rs");
    println!("cargo:rerun-if-changed=build.rs");
    let mut s = String::new();
    writeln!(s, "// Generated by build.rs from gfx-dsp/src/shapers.rs. Do not edit.").unwrap();
    writeln!(s, "pub static COMP_TABLES: [[f32; {}]; {}] = [", curves::COMP_POINTS, curves::COMPS.len()).unwrap();
    for c in curves::COMPS {
        let t = curves::comp_table(c);
        write!(s, "    // {c:?}\n    [").unwrap();
        for v in t {
            write!(s, "{:?}, ", v as f32).unwrap();
        }
        writeln!(s, "],").unwrap();
    }
    writeln!(s, "];").unwrap();
    let out = std::path::PathBuf::from(std::env::var("OUT_DIR").unwrap()).join("comp_tables.rs");
    std::fs::write(out, s).unwrap();
}
